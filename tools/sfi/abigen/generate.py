"""Deterministic Kiln C ABI -> Rust, using only Python stdlib and installed clang.

Run through the project's build limiter. Clang parses each public header independently;
no Windows SDK, libclang package, Windows executable, or handwritten C layout is used.
"""
import argparse
import ast
import hashlib
import json
from pathlib import Path
import re
import struct
import subprocess
import sys
import tempfile

TARGET = 'x86_64-pc-windows-msvc'
BANNER = '// SPDX-License-Identifier: MIT\n// @generated by tools/sfi/abigen/generate.py; do not edit.\n'
SCALARS = {
    'void': 'core::ffi::c_void', 'char': 'core::ffi::c_char',
    'signed char': 'i8', 'unsigned char': 'u8', '_Bool': 'bool', 'bool': 'bool',
    'short': 'i16', 'unsigned short': 'u16', 'int': 'i32', 'unsigned int': 'u32',
    'long': 'i32', 'unsigned long': 'u32', 'long long': 'i64', 'unsigned long long': 'u64',
    'int8_t': 'i8', 'uint8_t': 'u8', 'int16_t': 'i16', 'uint16_t': 'u16',
    'int32_t': 'i32', 'uint32_t': 'u32', 'int64_t': 'i64', 'uint64_t': 'u64',
    'intptr_t': 'isize', 'uintptr_t': 'usize', 'size_t': 'usize',
    'float': 'f32', 'double': 'f64',
}
KEYWORDS = set('as break const continue crate else enum extern false fn for if impl in let loop match mod move mut pub ref return self Self static struct super trait true type unsafe use where while async await dyn union'.split())


class GenerationError(RuntimeError):
    pass


def ident(name):
    if name in ('self', 'Self', 'super', 'crate'):
        return name + '_'
    return 'r#' + name if name in KEYWORDS else name


def rust_type(ctype):
    original = ctype
    ctype = ctype.replace(' __attribute__((cdecl))', '').strip()
    # No non-cdecl ABI is allowed to become an accidental extern C declaration.
    if '__attribute__' in ctype:
        raise GenerationError('unsupported calling convention/type: ' + original)
    function = re.fullmatch(r'(.*?)\(\*\)\((.*)\)', ctype)
    if function:
        ret, args = function.groups()
        args = args.strip()
        if '...' in args:
            raise GenerationError('variadic function pointer: ' + original)
        params = [] if args in ('', 'void') else [rust_type(a.strip()) for a in args.split(',')]
        result = '' if ret.strip() == 'void' else ' -> ' + rust_type(ret.strip())
        return 'Option<unsafe extern "C" fn(' + ', '.join(params) + ')' + result + '>'
    array = re.fullmatch(r'(.+?)((?:\[\d+\])+)', ctype)
    if array:
        base, bounds = array.groups()
        value = rust_type(base.strip())
        for bound in reversed(re.findall(r'\[(\d+)\]', bounds)):
            value = '[' + value + '; ' + bound + ']'
        return value
    # Discard only top-level qualifiers; pointee constness must survive each star.
    ctype = re.sub(r'\b(const|volatile|restrict)$', '', ctype).strip()
    if ctype.endswith('*'):
        pointee = ctype[:-1].strip()
        is_const = bool(re.search(r'(^const\s|\sconst$)', pointee))
        # Leading const belongs to the base pointee, not an intervening pointer.
        if '*' in pointee:
            is_const = bool(re.search(r'\bconst$', pointee))
        return ('*const ' if is_const else '*mut ') + rust_type(pointee)
    ctype = re.sub(r'^(const|volatile|restrict)\s+', '', ctype)
    ctype = re.sub(r'^(struct|union|enum)\s+', '', ctype)
    if ctype in SCALARS:
        return SCALARS[ctype]
    if re.fullmatch(r'Kiln\w+', ctype):
        return ident(ctype)
    raise GenerationError('unsupported C type: ' + original)


def run(clang, root, source, *extra):
    cmd = [clang, '--target=' + TARGET, '-std=c11', '-ffreestanding', '-Werror',
           '-I', str(root), *extra, str(source)]
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode:
        raise GenerationError('clang failed:\n' + result.stderr)
    return result.stdout


def walk(node):
    yield node
    for child in node.get('inner', []):
        yield from walk(child)


def own_nodes(tree, header):
    current = None
    for node in tree.get('inner', []):
        loc = node.get('loc', {})
        current = loc.get('file', current)
        if current and Path(current).resolve() == header.resolve():
            yield node


def record(node, name, ctype):
    fields, nested = [], []
    anonymous = None
    for child in node.get('inner', []):
        kind = child['kind']
        if kind == 'RecordDecl':
            if child.get('name'):
                raise GenerationError('unsupported nested named record in ' + name)
            anonymous = child
        elif kind == 'FieldDecl':
            if child.get('isBitfield'):
                raise GenerationError('unsupported bitfield: ' + name + '.' + child.get('name', '?'))
            fname = child.get('name')
            if not fname:
                raise GenerationError('unsupported anonymous promoted field in ' + name)
            ft = child['type']['qualType']
            if anonymous is not None:
                nested_name = name + '_' + fname
                nested.extend(record(anonymous, nested_name, '__typeof__(((' + ctype + '*)0)->' + fname + ')'))
                ft = nested_name
                anonymous = None
            fields.append((fname, rust_type(ft)))
        elif kind.endswith('Attr') and kind != 'MaxFieldAlignmentAttr':
            raise GenerationError('unsupported layout attribute: ' + name + ' ' + kind)
    return nested + [{'name': name, 'ctype': ctype, 'kind': node['tagUsed'], 'fields': fields}]


def macro_definitions(header, preprocessed):
    # -E -dD preserves defining-file line markers and only active definitions.
    # Track the final definition, including #undef, before assigning ownership.
    active, current = {}, None
    for line in preprocessed.splitlines():
        marker = re.match(r'^# \d+ "([^"]+)"', line)
        if marker:
            current = None if marker[1].startswith('<') else Path(marker[1]).resolve()
            continue
        definition = re.match(r'^#define (KILN_\w+)(.*)', line)
        removed = re.match(r'^#undef (KILN_\w+)\b', line)
        if definition:
            active[definition[1]] = (current, definition[2])
        elif removed:
            active.pop(removed[1], None)
    objects, functions = [], []
    for name, (owner, tail) in sorted(active.items()):
        if owner != header.resolve():
            continue
        if tail.startswith('('):
            functions.append(name)
        elif tail.strip() and name not in ('KILN_CALL', 'KILN_EXPORT'):
            objects.append((name, tail.strip()))
    return objects, functions


def ir_bytes(ir, name):
    match = re.search(r'^@' + re.escape(name) + r' = .*?constant \[(\d+) x i8\] (c"([^"]*)"|zeroinitializer)', ir, re.M)
    if not match:
        raise GenerationError('unsupported compiled byte constant: ' + name)
    size = int(match[1])
    if match[2] == 'zeroinitializer':
        return bytes(size)
    raw, result, i = match[3], bytearray(), 0
    while i < len(raw):
        if raw[i:i + 2] == '\\\\':
            result.append(0x5c)
            i += 2
        elif raw[i] == '\\':
            result.append(int(raw[i + 1:i + 3], 16))
            i += 3
        else:
            result.append(ord(raw[i]))
            i += 1
    if len(result) != size:
        raise GenerationError('compiled byte length mismatch: ' + name)
    return bytes(result)


def byte_literal(data):
    return 'b"' + ''.join(chr(b) if 32 <= b < 127 and b not in (34, 92) else ('\\0' if b == 0 else '\\x%02x' % b) for b in data) + '"'


def float_literal(ty, value):
    # The shortest Rust literal that gives the compiled value again (f32: through single precision).
    if value != value or value in (float('inf'), float('-inf')):
        raise GenerationError('unsupported non-finite float constant')
    if ty == 'f64':
        text = repr(value)
    else:
        single = struct.unpack('<f', struct.pack('<f', value))[0]
        if single != value:
            raise GenerationError('float constant is not a single-precision value')
        text = next(t for t in ('%.*g' % (p, value) for p in range(1, 10))
                    if struct.unpack('<f', struct.pack('<f', float(t)))[0] == value)
    return text if any(c in text for c in '.e') else text + '.0'


def ir_integer(ir, name):
    value = re.search(r'^@' + re.escape(name) + r' = .*?constant i(\d+) (-?\d+)', ir, re.M)
    if not value:
        raise GenerationError('non-integer/unsupported constant: ' + name)
    return int(value[1]), int(value[2])


def generate_header(root, relative, clang, tmp):
    header = root / relative
    source = tmp / 'header.c'
    source.write_text('#include "' + relative.as_posix() + '"\n')
    tree = json.loads(run(clang, root, source, '-Xclang', '-ast-dump=json', '-fsyntax-only'))
    records, aliases, constants, helpers, opaque = [], [], [], [], []
    nodes = list(own_nodes(tree, header))
    record_names = {n.get('name') for n in nodes if n['kind'] == 'RecordDecl' and n.get('completeDefinition')}
    enums = {n['name'] for n in nodes if n['kind'] == 'EnumDecl' and n.get('name')}
    for node in nodes:
        kind, name = node['kind'], node.get('name', '')
        if kind == 'RecordDecl' and node.get('completeDefinition'):
            if not name.startswith('Kiln'):
                raise GenerationError('unrecognized public record: ' + name)
            records.extend(record(node, name, node['tagUsed'] + ' ' + name))
        elif kind == 'TypedefDecl' and name.startswith('Kiln'):
            if name not in record_names:
                ctype = node['type']['qualType']
                # Windows MSVC enums use int unless explicitly made wider (then fail closed below).
                if ctype in ('struct ' + name, 'union ' + name):
                    opaque.append(name)
                else:
                    aliases.append((name, 'i32' if name in enums else rust_type(ctype)))
        elif kind == 'EnumDecl':
            previous = -1
            for child in node.get('inner', []):
                if child['kind'] != 'EnumConstantDecl':
                    continue
                values = [n['value'] for n in walk(child) if n['kind'] == 'ConstantExpr' and 'value' in n]
                value = int(values[0]) if values else previous + 1
                previous = value
                ty = rust_type(child['type']['qualType'])
                integer_type = re.fullmatch(r'([iu])(\d+)', ty)
                if not integer_type:
                    raise GenerationError('unsupported enum constant type: ' + ty)
                width = int(integer_type[2])
                value %= 1 << width
                if integer_type[1] == 'i' and value >= 1 << (width - 1):
                    value -= 1 << width
                constants.append((child['name'], ty, str(value)))
        elif kind == 'FunctionDecl':
            helpers.append(name)
    objects, function_macros = macro_definitions(header, run(clang, root, source, '-E', '-dD'))
    probe = ['#include "' + relative.as_posix() + '"']
    enum_constants = list(constants)
    for i, (name, _, _) in enumerate(enum_constants):
        probe.append('const __typeof__(' + name + ') sfi_enum_' + str(i) + ' = ' + name + ';')
    layout_queries = []
    for r in records:
        for key, expression in [('@size', 'sizeof(' + r['ctype'] + ')'), ('@align', '_Alignof(' + r['ctype'] + ')')]:
            layout_queries.append((r['name'], key, expression))
        for field, _ in r['fields']:
            layout_queries.append((r['name'], field, '__builtin_offsetof(' + r['ctype'] + ', ' + field + ')'))
    # Assert the width of named enum aliases rather than assuming a future enum remains int.
    for name, ty in aliases:
        if name in enums:
            probe.append('_Static_assert(sizeof(' + name + ')==4, "enum width");')
    for i, (_, _, expr) in enumerate(layout_queries):
        probe.append('const unsigned long long sfi_layout_' + str(i) + ' = ' + expr + ';')
    integer_macros, string_macros = [], []
    for name, value in objects:
        if value.startswith('"'):
            i = len(string_macros)
            string_macros.append(name)
            probe.append('const char sfi_string_' + str(i) + '[] = ' + name + ';')
        elif value.startswith('{'):
            # Untyped byte initializer (the public network proof frame). Reject
            # aggregate/designated/non-byte forms rather than guess a C type.
            try:
                items = ast.literal_eval('[' + value[1:-1] + ']')
                values = [ord(v) if isinstance(v, str) and len(v) == 1 else v for v in items]
                if not values or any(type(v) is not int or not 0 <= v <= 255 for v in values):
                    raise ValueError('not bytes')
            except (SyntaxError, ValueError, TypeError) as e:
                raise GenerationError('unsupported initializer macro ' + name) from e
            probe.append('const unsigned char sfi_bytes_' + name + '[] = ' + name + ';')
            constants.append((name, '[u8; ' + str(len(values)) + ']', '[' + ', '.join(map(str, values)) + ']'))
        else:
            i = len(integer_macros)
            integer_macros.append(name)
            probe.append('const __typeof__(' + name + ') sfi_macro_' + str(i) + ' = ' + name + ';')
            probe.append('const unsigned char sfi_signed_' + str(i) + ' = (((__typeof__(' + name + '))-1) < 0);')
    source.write_text('\n'.join(probe) + '\n')
    ir = run(clang, root, source, '-S', '-emit-llvm', '-o', '-')
    for i, name in enumerate(string_macros):
        constants.append((name, '&[u8]', byte_literal(ir_bytes(ir, 'sfi_string_' + str(i)))))
    for i, (name, _, value) in enumerate(enum_constants):
        width, compiled = ir_integer(ir, 'sfi_enum_' + str(i))
        if compiled % (1 << width) != int(value) % (1 << width):
            raise GenerationError('enum constant disagrees with compiled C: ' + name)
    layouts = {r['name']: {'fields': {}} for r in records}
    checks = ['#include "' + relative.as_posix() + '"']
    for i, (name, key, expr) in enumerate(layout_queries):
        _, value = ir_integer(ir, 'sfi_layout_' + str(i))
        if key.startswith('@'):
            layouts[name][key[1:]] = value
        else:
            layouts[name]['fields'][key] = value
        checks.append('_Static_assert((' + expr + ') == ' + str(value) + ', "' + name + '.' + key + '");')
    source.write_text('\n'.join(checks) + '\n')
    run(clang, root, source, '-fsyntax-only')
    for i, name in enumerate(integer_macros):
        floating = re.search(r'^@sfi_macro_' + str(i) + r' = .*?constant (float|double) (-?[0-9.]+[eE][+-][0-9]+)', ir, re.M)
        if floating:
            constants.append((name, 'f32' if floating[1] == 'float' else 'f64', repr(float(floating[2]))))
            continue
        # clang prints a float constant in hex when its %e form would not give the value back: current LLVM as the
        # type's own bits (0.01f as f0x3C23D70A), older LLVM as the IEEE double's 64 bits, also for a float
        # (0x3F847AE140000000).
        floating = re.search(r'^@sfi_macro_' + str(i) + r' = .*?constant (float|double) (f?)0x([0-9A-Fa-f]+)\b', ir, re.M)
        if floating:
            ty = 'f32' if floating[1] == 'float' else 'f64'
            bits = floating[3]
            if floating[2] and ty == 'f32' and len(bits) == 8:
                value = struct.unpack('>f', bytes.fromhex(bits))[0]
            elif len(bits) == 16:
                value = struct.unpack('>d', bytes.fromhex(bits))[0]
            else:
                raise GenerationError('unsupported hex float constant ' + name)
            constants.append((name, ty, float_literal(ty, value)))
            continue
        width, value = ir_integer(ir, 'sfi_macro_' + str(i))
        _, signed = ir_integer(ir, 'sfi_signed_' + str(i))
        if width not in (8, 16, 32, 64):
            raise GenerationError('unsupported constant width ' + name)
        if not signed:
            value %= 1 << width
        constants.append((name, ('i' if signed else 'u') + str(width), str(value)))
    dependencies = re.findall(r'^\s*#include\s+"(kiln_\w+)\.h"', header.read_text(), re.M)
    text = [BANNER, '#![allow(non_camel_case_types, non_snake_case, non_upper_case_globals, unused_imports)]\n']
    if relative.name != 'kiln_api.h':
        text.append('use crate::*;\n')
        for dep in sorted(set(dependencies)):
            text.append('pub use super::' + dep + '::*;\n')
    for name in opaque:
        text.append('#[repr(C)]\npub struct ' + name + ' { _private: [u8; 0] }\n')
    for name, ty in aliases:
        text.append('pub type ' + ident(name) + ' = ' + ty + ';\n')
    for name, ty, value in sorted(constants):
        text.append('pub const ' + name + ': ' + ty + ' = ' + value + ';\n')
    for r in records:
        text.extend(['\n#[repr(C)]\n#[derive(Clone, Copy)]\n', 'pub ' + r['kind'] + ' ' + r['name'] + ' {\n'])
        text.extend('    pub ' + ident(f) + ': ' + t + ',\n' for f, t in r['fields'])
        text.append('}\n')
    return ''.join(text), records, layouts, {'function_macros': function_macros, 'inline_helpers': sorted(helpers)}


def generate(root, clang):
    root = Path(root).resolve()
    abi = Path('native/core/abi')
    headers = [abi / 'kiln_api.h', *sorted((root / abi / 'services').glob('*.h'))]
    headers = [p.relative_to(root) if p.is_absolute() else p for p in headers]
    if not (root / headers[0]).is_file():
        raise GenerationError('missing native/core/abi/kiln_api.h')
    outputs, inventory, names = {}, {}, {}
    assertions = [BANNER, '#[cfg(target_pointer_width = "64")]\nconst _: () = {\n']
    with tempfile.TemporaryDirectory(prefix='kiln-abigen-') as directory:
        tmp = Path(directory)
        for relative in headers:
            try:
                text, records, layouts, ignored = generate_header(root, relative, clang, tmp)
            except GenerationError as error:
                raise GenerationError(relative.as_posix() + ': ' + str(error)) from error
            core = relative.name == 'kiln_api.h'
            module = relative.stem
            outputs['src/bindings.rs' if core else 'src/services/' + module + '.rs'] = text
            key = relative.as_posix()
            inventory[key] = {'sha256': hashlib.sha256((root / relative).read_bytes()).hexdigest(),
                              'layouts': layouts, **ignored}
            for r in records:
                name = r['name']
                names.setdefault(name, []).append({'header': key, 'layout': layouts[name], 'fields': r['fields']})
                rust = ('crate::' if core else 'crate::services::' + module + '::') + name
                assertions.append('    assert!(core::mem::size_of::<' + rust + '>() == ' + str(layouts[name]['size']) + ');\n')
                assertions.append('    assert!(core::mem::align_of::<' + rust + '>() == ' + str(layouts[name]['align']) + ');\n')
                for f, _ in r['fields']:
                    assertions.append('    assert!(core::mem::offset_of!(' + rust + ', ' + ident(f) + ') == ' + str(layouts[name]['fields'][f]) + ');\n')
    assertions.append('};\n')
    outputs['src/layout.rs'] = ''.join(assertions)
    outputs['src/services/mod.rs'] = BANNER + ''.join('pub mod ' + h.stem + ';\n' for h in headers[1:])
    collisions = {n: entries for n, entries in names.items() if len(entries) > 1}
    output_hashes = {p: hashlib.sha256(content.encode('utf-8')).hexdigest() for p, content in sorted(outputs.items())}
    outputs['abi-manifest.json'] = json.dumps({'schema': 1, 'target': TARGET, 'headers': inventory,
        'name_collisions': collisions, 'outputs': output_hashes}, indent=2, sort_keys=True) + '\n'
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[3])
    parser.add_argument('--clang', default='clang')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        outputs = generate(args.root, args.clang)
        target = args.root / 'crates/sfi/kiln-abi'
        drift = []
        for relative, content in outputs.items():
            path = target / relative
            if args.check:
                if not path.is_file() or path.read_text(encoding='utf-8') != content:
                    drift.append(relative)
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding='utf-8', newline='\n')
        # A removed service header must not leave a stale generated module behind.
        if target.exists():
            for path in target.glob('src/services/*.rs'):
                if path.relative_to(target).as_posix() not in outputs:
                    drift.append(path.relative_to(target).as_posix() + ' (obsolete; remove explicitly)')
        if drift:
            print('drift: ' + ', '.join(drift), file=sys.stderr)
            return 1
        print(('checked' if args.check else 'generated') + ' Kiln ABI: ' + str(len(outputs)) + ' files, target ' + TARGET)
        return 0
    except (GenerationError, OSError, ValueError) as error:
        print(str(error), file=sys.stderr)
        return 2


if __name__ == '__main__':
    sys.exit(main())
