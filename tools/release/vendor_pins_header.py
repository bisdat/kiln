#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""Writes the game side's copy of the vendor pins, native/services/ui/vendor_pins.h, from the launcher's manifest
(launcher/src/data/vendor-components.json). The launcher pins each vendor file's size and SHA-256 and checks downloads
against them; the game checks the same values again before it loads a file (vendor_file.h). One source of truth: the
manifest. This header is generated from it and kiln.ui's host tests fail when the two differ (--check).

  python3 -I tools/release/vendor_pins_header.py           # prints what it would write
  python3 -I tools/release/vendor_pins_header.py --write   # writes the header
  python3 -I tools/release/vendor_pins_header.py --check   # exit 1 unless the header is what the manifest makes

A file the manifest has not pinned yet ("sha256": "not-pinned") is left out: the game loads no file it cannot check.
Exit 0: done; 1: the header differs (--check) or the manifest is not usable; 2: usage.
"""
import argparse
import json
from pathlib import Path
import re
import sys

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
MANIFEST = REPO / "launcher" / "src" / "data" / "vendor-components.json"
HEADER = REPO / "native" / "services" / "ui" / "vendor_pins.h"
NOT_PINNED = "not-pinned"
SAFE = re.compile(r"^[A-Za-z0-9._-]+$")


def render(manifest):
    """The header's text for a parsed manifest. Raises ValueError for a value the game could not use safely."""
    if manifest.get("format") != 1:
        raise ValueError(f"format {manifest.get('format')} is not 1")
    rows = []
    for c in manifest.get("components", []):
        for key in ("id", "vendor", "version"):
            if not SAFE.match(str(c.get(key, ""))):
                raise ValueError(f"component {c.get('id')!r}: {key} {c.get(key)!r} is not a plain name")
        for f in c.get("files", []):
            name, size, sha = f.get("name", ""), f.get("size"), f.get("sha256", NOT_PINNED)
            if not SAFE.match(name) or name in (".", ".."):
                raise ValueError(f"{c['id']}: file name {name!r} is not a plain name")
            if not isinstance(size, int) or size <= 0:
                raise ValueError(f"{c['id']}/{name}: size {size!r} is not a positive whole number")
            if sha == NOT_PINNED:
                rows.append(f"    // {c['id']}/{name}: not pinned in the manifest, so the game never loads it")
                continue
            if not re.match(r"^[0-9a-f]{64}$", sha):
                raise ValueError(f"{c['id']}/{name}: sha256 {sha!r} is not 64 lower-case hex digits")
            rows.append(f'    {{"{c["id"]}", "{c["vendor"]}", "{c["version"]}", "{name}", {size}u, "{sha}"}},')
    body = "\n".join(rows)
    return f"""// SPDX-License-Identifier: MIT
// GENERATED by tools/release/vendor_pins_header.py from launcher/src/data/vendor-components.json. Do not edit: change the
// manifest, then run the tool with --write. kiln.ui's host tests (tests/run.sh) fail when the two differ.
// The vendor files the game may load, each with the size and SHA-256 Kiln pinned (vendor_file.h checks them again before
// it loads a file from <game>/kiln/vendor/<vendor>/<version>/).
#pragma once
#include <cstdint>

namespace kui::vendor {{

struct Pin {{
    const char* component;  // the manifest's id ("intel-xess")
    const char* vendor;     // the folder kiln/vendor/<vendor>/
    const char* version;    // the folder kiln/vendor/<vendor>/<version>/
    const char* name;       // the file's name in that folder
    uint64_t size;
    const char* sha256;     // 64 lower-case hex digits
}};

inline constexpr Pin kPins[] = {{
{body}
}};

}}  // namespace kui::vendor
"""


def main(argv=None):
    ap = argparse.ArgumentParser(description="Write the game's copy of the vendor pins from the launcher's manifest.")
    ap.add_argument("--manifest", type=Path, default=MANIFEST)
    ap.add_argument("--header", type=Path, default=HEADER)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    if a.write and a.check:
        print("--write and --check do not go together", file=sys.stderr)
        return 2
    try:
        text = render(json.loads(a.manifest.read_text(encoding="utf-8")))
    except (OSError, ValueError) as e:
        print(f"{a.manifest}: {e}", file=sys.stderr)
        return 1
    if a.check:
        have = a.header.read_text(encoding="utf-8") if a.header.is_file() else None
        if have != text:
            print(f"{a.header} is not what {a.manifest} makes: run python3 -I tools/release/vendor_pins_header.py --write",
                  file=sys.stderr)
            return 1
        print(f"{a.header.name} matches the manifest")
        return 0
    if a.write:
        a.header.write_text(text, encoding="utf-8")
        print(f"wrote {a.header}")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
