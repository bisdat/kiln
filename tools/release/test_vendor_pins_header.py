"""Tests for tools/release/vendor_pins_header.py: the shipped header is what the shipped manifest makes (--check), a pin
lands in the header with its size and SHA-256, a file not pinned yet is left out, and names the game could not use
safely (a path, a quote) are refused. Nothing is downloaded.

  python3 -I tools/release/test_vendor_pins_header.py
"""
import contextlib
import importlib.util
import io
import json
from pathlib import Path
import tempfile
import unittest

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("vendor_pins_header", HERE / "vendor_pins_header.py")
vph = importlib.util.module_from_spec(spec)
spec.loader.exec_module(vph)

SHA = "ab" * 32


def manifest(**over):
    f = {"name": "libxess.dll", "url": "https://example.invalid/libxess.dll", "size": 10, "sha256": SHA}
    f.update(over)
    return {"format": 1, "components": [{"id": "intel-xess", "vendor": "intel", "version": "3.0.2", "files": [f]}]}


class Render(unittest.TestCase):
    def test_shipped_header_matches_the_manifest(self):
        with contextlib.redirect_stdout(io.StringIO()):
            self.assertEqual(vph.main(["--check"]), 0)

    def test_a_pin_and_its_values(self):
        text = vph.render(manifest())
        self.assertIn('{"intel-xess", "intel", "3.0.2", "libxess.dll", 10u, "' + SHA + '"},', text)
        self.assertIn("GENERATED by tools/release/vendor_pins_header.py", text)

    def test_not_pinned_is_left_out(self):
        text = vph.render(manifest(sha256="not-pinned"))
        self.assertNotIn('"libxess.dll", 10u', text)
        self.assertIn("intel-xess/libxess.dll: not pinned", text)

    def test_unsafe_values_are_refused(self):
        for bad in ({"name": "../libxess.dll"}, {"name": "a\\b.dll"}, {"name": 'x".dll'}, {"name": ".."}, {"size": 0},
                    {"size": "10"}, {"sha256": "AB" * 32}, {"sha256": "ab" * 31}):
            with self.subTest(bad=bad):
                with self.assertRaises(ValueError):
                    vph.render(manifest(**bad))
        m = manifest()
        m["components"][0]["version"] = "3.0.2/../../x"
        with self.assertRaises(ValueError):
            vph.render(m)
        m = manifest()
        m["format"] = 2
        with self.assertRaises(ValueError):
            vph.render(m)

    def test_check_fails_on_a_stale_header(self):
        with tempfile.TemporaryDirectory() as d:
            man = Path(d) / "m.json"
            hdr = Path(d) / "h.h"
            man.write_text(json.dumps(manifest()), encoding="utf-8")
            hdr.write_text("// old\n", encoding="utf-8")
            with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
                self.assertEqual(vph.main(["--check", "--manifest", str(man), "--header", str(hdr)]), 1)
                self.assertEqual(vph.main(["--write", "--manifest", str(man), "--header", str(hdr)]), 0)
                self.assertEqual(vph.main(["--check", "--manifest", str(man), "--header", str(hdr)]), 0)
                self.assertEqual(vph.main(["--check", "--write"]), 2)


if __name__ == "__main__":
    unittest.main()
