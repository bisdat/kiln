"""The API reference's table of contents by assembly, an overview page, and one page for each service.

  tools/docs-site/services.py [--services <services.json>] <api folder> <stage folder>

Run after the second `docfx metadata`: <api folder> holds the ManagedReference YAML (one file per type), <stage folder> the
annotated Kiln.*.xml docs. DocFX writes toc.yml as one namespace (`Kiln`) holding every type, 4,000 of them in one flat list;
this replaces it with one group per assembly, a service of Kiln or Kiln.Api itself, from each item's `assemblies:` field.
  api/toc.yml                       Overview, then Kiln.Api, Kiln.Game, Kiln.Testing, Kiln.TestKit, the services (A-Z), the namespaces
  api/index.md                      the overview: every assembly with its KilnServices name, summary and guide
  api/services/<assembly>.md        the service's page: facts, guide, capabilities, samples and every type with its first sentence
The facts of a service come from services.json (gen-services.py writes it from the repository); an assembly it does not know
still gets its group and a page of its types. Standard library only.
"""
import argparse
import importlib.util
import json
from pathlib import Path
import sys
import xml.etree.ElementTree as ET

HERE = Path(__file__).resolve().parent
TYPES = ("Class", "Struct", "Enum", "Interface", "Delegate")
FIRST = ("Kiln.Api", "Kiln.Game", "Kiln.Testing", "Kiln.TestKit")
REPOSITORY = "https://github.com/frostdev-ops/kiln"
GENERATED_ROOT = "Kiln.Ecs."          # the game's types generated by typegen: thousands, listed on the Kiln.Ecs page


def load(name, filename):
    spec = importlib.util.spec_from_file_location(name, HERE / filename)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


undocumented = load("undocumented", "undocumented.py")
docxml = load("docxml", "docxml.py")


def read_items(api):
    """[(item, file name)] of every item of the folder's YAML."""
    return [(i, f.name) for f in sorted(Path(api).glob("*.yml")) if f.name != "toc.yml" for i in undocumented.items(f)]


def read_summaries(stage):
    """{documentation id: first sentence of its summary} of the stage's XML docs."""
    out = {}
    for f in sorted(Path(stage).glob("Kiln.*.xml")):
        for m in ET.parse(f).iter("member"):
            s = m.find("summary")
            if s is not None:
                out[m.get("name")] = docxml.first_sentence(s)
    return out


def display(item, assembly):
    """The name a type has in the table of contents: DocFX's, with its namespace when it is not the assembly's own."""
    name = item.get("name") or item["uid"].rsplit(".", 1)[-1]
    ns = item.get("namespace") or ""
    if ns and ns not in ("Kiln", assembly) and ns.startswith(assembly + "."):
        name = ns[len(assembly) + 1:] + "." + name
    return name


def group(items):
    """{assembly: [(type item, file)]}: the types of the reference by assembly (the first one an item names)."""
    out = {}
    for item, file in items:
        if item.get("type") in TYPES and item.get("assemblies"):
            out.setdefault(item["assemblies"][0], []).append((item, file))
    return out


def order(assemblies):
    first = [a for a in FIRST if a in assemblies]
    return first + sorted(a for a in assemblies if a not in FIRST)


def quote(text):
    return json.dumps(text, ensure_ascii=False)


def toc(items, by_assembly):
    lines = ["### YamlMime:TableOfContent", "- name: Overview", "  href: index.md"]
    for asm in order(by_assembly):
        lines += [f"- name: {quote(asm)}", f"  href: services/{asm}.md", "  items:"]
        for item, _ in sorted(by_assembly[asm], key=lambda x: (display(x[0], asm).lower(), display(x[0], asm))):
            lines += [f"  - uid: {quote(item['uid'])}", f"    name: {quote(display(item, asm))}", f"    type: {item['type']}"]
    spaces = sorted((i for i, _ in items if i.get("type") == "Namespace"), key=lambda i: i["uid"])
    if spaces:
        lines += ["- name: Namespaces", "  items:"]
        for ns in spaces:
            lines += [f"  - uid: {quote(ns['uid'])}", f"    name: {quote(ns.get('name') or ns['uid'])}", "    type: Namespace"]
    return "\n".join(lines) + "\n"


def guide_link(path, up="../../"):
    """(label, href) of a guide page of the repository, from a page `up` folders below the site's root: the site's own copy
    of a modding guide, else the page in the repository."""
    label = path.rsplit("/", 1)[-1]
    if path.startswith("docs/kiln/modding/"):
        return label, up + "modding/" + path[len("docs/kiln/modding/"):]
    return label, f"{REPOSITORY}/blob/main/{path}"


def esc(text):
    """Text for a Markdown table cell or list line: `<T>` is no tag, a pipe no cell break."""
    return text.replace("<", "&lt;").replace(">", "&gt;").replace("|", "\\|").replace("\n", " ")


def landing(asm, info, types, summaries):
    info = info or {}
    name = info.get("name")
    out = ["---", f"title: {quote(asm)}", "---", f"# {asm}", ""]
    if info.get("summary"):
        out += [esc(info["summary"]).rstrip(".") + ".", ""]
    rows = [("Assembly", f"`{asm}.dll`")]
    if name:
        rows.append(("KilnServices name", f"`{name}`"))
    elif asm == "Kiln.TestKit":
        rows.append(("Package", "`Kiln.TestKit` (NuGet), for a test project that runs under `dotnet test`"))
    else:
        rows.append(("KilnServices name", "none: every mod has it"))
    if info.get("guides"):
        rows.append(("Guide", ", ".join("[{}]({})".format(*guide_link(g)) for g in info["guides"])))
    rows.append(("Types", str(len(types))))
    out += [f"- **{k}:** {v}" for k, v in rows] + [""]
    if name:
        out += [f"Use it from a mod: put `<KilnServices>{name}</KilnServices>` in the mod's project file "
                "([Kiln.Sdk](../../modding/mdk.md)).", ""]
    if info.get("capabilities"):
        out += ["## Capabilities", "",
                "What a member of this assembly needs from the game build before it works (`Capabilities.Is(\"name\")`; "
                f"[what the names mean]({REPOSITORY}/blob/main/docs/kiln/services/caps.md)).", "",
                "| Capability | Members that need it |", "|---|---:|"]
        out += [f"| `{c['name']}` | {c['members']} |" for c in info["capabilities"]] + [""]
    if info.get("samples"):
        out += ["## Samples", "", "Mods in the repository that use this service:", ""]
        out += [f"- [{s}]({REPOSITORY}/tree/main/mods/samples/{s})" for s in info["samples"]] + [""]
    # a list, not a table: DocFX's Markdown parser stops at "elements too deeply nested" on a table of a few hundred rows
    out += ["## Types", ""]
    listed = [(i, f) for i, f in types if not i["uid"].startswith(GENERATED_ROOT)]
    for item, file in sorted(listed, key=lambda x: (display(x[0], asm).lower(), display(x[0], asm))):
        label = esc(display(item, asm))
        summary = esc(summaries.get(item.get("commentId"), "")).replace("\\|", "|")
        out.append(f"- [{label}](../{file}) ({item['type'].lower()})" + (f": {summary}" if summary else ""))
    if len(listed) != len(types):
        out += ["", f"The {len(types) - len(listed)} game types generated into `Ecs` are on the page of [`Ecs`](../Kiln.Ecs.yml)."]
    return "\n".join(out) + "\n"


def overview(by_assembly, known):
    out = ["# Kiln API reference", "",
           "Every public type and member a mod can use, by the assembly it lives in. Each assembly is a Kiln service (`<KilnServices>` "
           "in the mod's project file) or part of the core every mod has. Each type and member says since which mod API it exists "
           "(`Since mod API 0.2.12 (0.2.0-dev.30)`), on which thread it may run and on which side, and which capabilities it needs.", "",
           "| Assembly | KilnServices | What it is | Guide |", "|---|---|---|---|"]
    for asm in order(by_assembly):
        info = known.get(asm) or {}
        guides = ", ".join("[{}]({})".format(*guide_link(g, "../")) for g in (info.get("guides") or [])[:2])
        out.append(f"| [{asm}](services/{asm}.md) | {('`' + info['name'] + '`') if info.get('name') else ''} | "
                   f"{esc((info.get('summary') or '').rstrip('.'))} | {guides} |")
    out += ["", "[All types of the namespace `Kiln`](Kiln.yml), in one list.", ""]
    return "\n".join(out)


def build(api, stage, services_json):
    api = Path(api)
    items = read_items(api)
    by_assembly = group(items)
    known = {s["assembly"]: s for s in json.loads(Path(services_json).read_text(encoding="utf-8"))["services"]} \
        if services_json and Path(services_json).is_file() else {}
    summaries = read_summaries(stage)
    (api / "services").mkdir(exist_ok=True)
    for asm, types in by_assembly.items():
        (api / "services" / f"{asm}.md").write_text(landing(asm, known.get(asm), types, summaries), encoding="utf-8")
    (api / "index.md").write_text(overview(by_assembly, known), encoding="utf-8")
    (api / "toc.yml").write_text(toc(items, by_assembly), encoding="utf-8")
    return by_assembly


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--services", default=str(HERE / "services.json"))
    ap.add_argument("api")
    ap.add_argument("stage")
    a = ap.parse_args()
    if not Path(a.api).is_dir():
        sys.exit(f"no api folder {a.api}")
    by_assembly = build(a.api, a.stage, a.services)
    print(f"services: {len(by_assembly)} assemblies, {sum(len(v) for v in by_assembly.values())} types in the table of contents")


if __name__ == "__main__":
    main()
