#!/usr/bin/env bash
# Regenerates mv_convert_spv.h from mv_convert.comp (glslc from the Vulkan SDK or shaderc; spirv-val checks it).
set -euo pipefail
cd "$(dirname "$0")"
t=$(mktemp -d)
trap 'rm -rf "${t:?}"' EXIT
glslc --target-env=vulkan1.1 -O -o "$t/mv.spv" mv_convert.comp
spirv-val --target-env vulkan1.1 "$t/mv.spv"
{
  echo "// SPDX-License-Identifier: MIT"
  echo "// Generated by gen_mv_convert.sh from mv_convert.comp: do not edit."
  echo "#pragma once"
  echo "#include <cstdint>"
  echo "namespace kui::upscale {"
  echo "inline constexpr uint32_t kMvConvertSpv[] = {"
  od -An -v -t x4 -w16 "$t/mv.spv" | sed -E 's/ +/ 0x/g; s/^ //; s/ /, /g; s/$/,/; s/^/    /'
  echo "};"
  echo "}  // namespace kui::upscale"
} > mv_convert_spv.h
