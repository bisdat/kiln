#!/usr/bin/env bash
# Regenerates output_probe_spv.h from output_probe.comp (glslc from the Vulkan SDK or shaderc; spirv-val checks it).
set -euo pipefail
cd "$(dirname "$0")"
t=$(mktemp -d)
trap 'rm -rf "${t:?}"' EXIT
glslc --target-env=vulkan1.1 -O -o "$t/probe.spv" output_probe.comp
spirv-val --target-env vulkan1.1 "$t/probe.spv"
{
  echo "// SPDX-License-Identifier: MIT"
  echo "// Generated by gen_output_probe.sh from output_probe.comp: do not edit."
  echo "#pragma once"
  echo "#include <cstdint>"
  echo "namespace kui::upscale {"
  echo "inline constexpr uint32_t kOutputProbeSpv[] = {"
  od -An -v -t x4 -w16 "$t/probe.spv" | sed -E 's/ +/ 0x/g; s/^ //; s/ /, /g; s/$/,/; s/^/    /'
  echo "};"
  echo "}  // namespace kui::upscale"
} > output_probe_spv.h
