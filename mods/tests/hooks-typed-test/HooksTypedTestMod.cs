using System.Diagnostics;
using System.Runtime.InteropServices;
using System.Text.Json;
using Kiln;
using Kiln.Sigs;
using GetGameTime = Kiln.Sigs.Time.GetGameTime;
using SetTimeScale = Kiln.Sigs.Time.SetTimeScale;
using Volume = Kiln.Sigs.Items.GetItemVolume;
using AttrChanged = Kiln.Sigs.Items.AttrChanged;
using OwnVolume = Kiln.Sigs.HooksTypedTest.ItemVolume;

namespace HooksTypedTest;

/// <summary>
/// Lab test of typed hooks and calls (chapter 06b §6, §9.10), player-free. Rows: the capability rows; what the native
/// part (native/, kiln-hooks-typed-test.dll in kiln/plugins) saw at boot through typed links on RegisterNative (argc from
/// the caller's stack against natives.json) and SetTimeScale (a float in xmm1); a wrong descriptor refused naming its
/// argument; SetTimeScale through a managed handler (Invoke round trip, skipped so the clock is untouched);
/// GetItemVolume's struct return by value from Invoke and changed after the original; two handlers where the first
/// skips; a handler that throws after CallOriginal; a descriptor of the mod's own fragment (generated by the Kiln.Sigs
/// generator); the cost per call; and, with the lab parallel switch (kiln/control/systems.parallel), a typed hook on
/// items/AttrChanged on worker threads, where a tick descriptor's Invoke must throw. GetItemVolume is only ever called
/// with a null item (the game's own null branch: {18, 1}), so nothing of the world is read or changed. Prints
/// "hooks-typed-test: PASS|FAIL ..." lines and "hooks-typed-test: done, N PASS, M FAIL". The full run is the first load
/// of the process; a hot reload (reload-test hooks-typed-test 20) installs one typed hook, calls through it and leaves.
/// </summary>
public sealed class HooksTypedTestMod : Mod
{
    private const string KeepKey = "hooks-typed-test.loads";
    private int _pass, _fail;
    private readonly List<string> _skipped = [];
    private readonly List<HookHandle> _hooks = [];
    private nint _fake;  // a zeroed block that stands in for a Daytime the game never sees

    private void Check(bool ok, string what)
    {
        if (ok) _pass++; else _fail++;
        Log.Info($"hooks-typed-test: {(ok ? "PASS" : "FAIL")} {what}");
    }

    public override void OnLoad()
    {
        _fake = Marshal.AllocHGlobal(4096);
        Marshal.Copy(new byte[4096], 0, _fake, 4096);
        var load = Keep.Span<int>(KeepKey, 1)[0] += 1;
        if (load > 1)
        {
            // a hot reload: one typed hook installed, one call through it; the unload takes it off again
            var calls = 0;
            var r = Volume.Detour((ref Volume.Call c) => { Interlocked.Increment(ref calls); c.CallOriginal(); });
            if (r.Ok) _hooks.Add(r.Handle!);
            var v = Volume.Invoke(0);
            if (!r.Ok || r.Handle?.State != HookRegistrationState.Installed || calls != 1 || v.Value != 18 || v.Has != 1)
                Log.Error($"hooks-typed-test: FAIL reload {load}: hook {r.Handle?.State} ({r.Handle?.Reason ?? r.Reason}), handler calls {calls}, Invoke {{{v.Value},{v.Has}}}");
            else Log.Info($"hooks-typed-test: PASS reload {load}: installed hook, one handler call, Invoke {{18,1}}");
            return;
        }
        _ = Run();
    }

    public override void OnUnload()
    {
        foreach (var h in _hooks) h.Remove();
        _hooks.Clear();
        if (_fake != 0) Marshal.FreeHGlobal(_fake);
        _fake = 0;
    }

    private HookHandle Hold(HookResult r, string what)
    {
        if (!r.Ok) throw new InvalidOperationException($"{what} was refused: {r.Reason}");
        _hooks.Add(r.Handle!);
        return r.Handle!;
    }

    [DllImport("kiln-hooks-typed-test.dll", EntryPoint = "kiln_typed_test_av", CallingConvention = CallingConvention.Cdecl)]
    private static extern void NativeAccessViolation();

    [DllImport("kernel32.dll")]
    private static extern nint VirtualAlloc(nint address, nuint size, uint type, uint protect);

    // Run BEFORE and AFTER in separate disposable lab processes. A CLR fail-fast is a FAILED boundary proof.
    // Control: kiln/control/hooks-typed-av-before OR hooks-typed-av-after OR hooks-typed-av-managed. Never enabled by the
    // normal lab run. (On .NET 10 the first two end the process: an access violation in native code under a managed frame
    // is a fail-fast of the runtime, 0xC0000005; see docs/kiln/services/hooks.md, Faults.)
    private void HardFaultResult()
    {
        var mods = Path.GetDirectoryName(Path.TrimEndingDirectorySeparator(Context.Info.Directory))!;
        var root = Path.GetDirectoryName(mods)!;
        if (File.Exists(Path.Combine(root, "control", "hooks-typed-av-managed"))) { ManagedFaults(); return; }
        var after = File.Exists(Path.Combine(root, "control", "hooks-typed-av-after"));
        if (!after && !File.Exists(Path.Combine(root, "control", "hooks-typed-av-before"))) return;
        var calls = 0;
        var count = Hold(Volume.Detour((ref Volume.Call c) => { Interlocked.Increment(ref calls); c.CallOriginal(); }, -10), "AV counter");
        var fault = Hold(Volume.Detour((ref Volume.Call c) =>
        {
            if (after) { c.CallOriginal(); c.Result.Value = 999; c.Result.Has = 0; }
            NativeAccessViolation();
        }, 10), "AV handler");
        var result = Volume.Invoke(0);
        Drop(fault); Drop(count);
        Check(calls == 1 && result.Value == 18 && result.Has == 1,
            $"AV {(after ? "after" : "before")} CallOriginal: struct result {{18,1}}, original once ({calls}), process continued");
    }

    // A hardware fault in the handler's own managed code after CallOriginal, having overwritten the struct: at the null
    // page (the runtime raises NullReferenceException) and then at a no-access page above 64 KiB (an
    // AccessViolationException, which .NET does not let managed code catch). The second may end the process: last.
    private unsafe void ManagedFaults()
    {
        foreach (var high in new[] { false, true })
        {
            var page = high ? VirtualAlloc(0, 4096, 0x3000 /* MEM_COMMIT | MEM_RESERVE */, 0x01 /* PAGE_NOACCESS */) : 0x10;
            var calls = 0;
            var count = Hold(Volume.Detour((ref Volume.Call c) => { Interlocked.Increment(ref calls); c.CallOriginal(); }, -10), "fault counter");
            var fault = Hold(Volume.Detour((ref Volume.Call c) =>
            {
                c.CallOriginal();
                c.Result.Value = 999;
                c.Result.Has = 0;
                *(int*)page = 1;
            }, 10), "fault handler");
            var what = high ? $"a write to a no-access page (0x{page:x}) in the handler's managed code" : "a write to the null page (0x10) in the handler's managed code";
            Log.Info($"hooks-typed-test: next: {what}, after CallOriginal");
            var result = Volume.Invoke(0);
            Drop(fault);
            Drop(count);
            Check(page != 0 && calls == 1 && result.Value == 18 && result.Has == 1,
                $"{what}, after CallOriginal: struct result {{{result.Value},{result.Has}}}, original once ({calls}), process continued");
        }
    }

    private void Drop(HookHandle h)
    {
        h.Remove();
        _hooks.Remove(h);
    }

    private async Task Run()
    {
        try
        {
            await Context.Scheduler.NextTick();
            Rows();
            Boot();
            await Context.Scheduler.NextTick();
            WrongDescriptor();
            TimeScale();
            ItemVolume();
            HardFaultResult();
            OwnFragment();
            Cost();
            await Workers();
        }
        catch (Exception e)
        {
            Check(false, $"the run stopped: {e.GetType().Name}: {e.Message}");
        }
        Log.Info($"hooks-typed-test: done, {_pass} PASS, {_fail} FAIL" +
                 (_skipped.Count > 0 ? $" ({_skipped.Count} row(s) not run here: {string.Join("; ", _skipped)})" : ""));
    }

    private void Rows()
    {
        string[] rows = [Volume.Capability, "sig/items/AttrFind", AttrChanged.Capability, SetTimeScale.Capability, GetGameTime.Capability,
            "sig/abilities/RegisterNative", "sig/world/ReadOther", "sig/GetComponent", "sig/rules/QuatRotate", "sig/weather/SampleAt"];
        var off = rows.Where(r => !Capabilities.Is(r)).ToList();
        Check(Capabilities.Is("hooks.typed") && off.Count == 0,
            $"hooks.typed and the ten sig rows are on ({(off.Count == 0 ? "all" : "off: " + string.Join(", ", off.Select(r => $"{r} ({Capabilities.Why(r)})")))})");
    }

    // what the native part recorded at boot
    private JsonElement? _boot;

    private void Boot()
    {
        var mods = Path.GetDirectoryName(Path.TrimEndingDirectorySeparator(Context.Info.Directory))!;  // <server>/kiln/mods
        var file = Path.Combine(Path.GetDirectoryName(mods)!, "logs", "hooks-typed-test-boot.json");
        if (!File.Exists(file))
        {
            Check(false, $"RegisterNative at boot: {file} is missing (is kiln-hooks-typed-test.dll in kiln/plugins?)");
            return;
        }
        var boot = JsonDocument.Parse(File.ReadAllText(file)).RootElement;
        _boot = boot;
        var natives = JsonDocument.Parse(File.ReadAllText(Path.Combine(Context.Info.Directory, "natives.json"))).RootElement
            .GetProperty("natives").EnumerateArray()
            .ToDictionary(n => n.GetProperty("hash").GetString()!.ToLowerInvariant(), n => (Name: n.GetProperty("name").GetString()!, Argc: n.GetProperty("argc").GetInt32()));
        var calls = boot.GetProperty("register_native_calls").GetInt32();
        int named = 0, equal = 0, garbage = 0;
        var wrong = new List<string>();
        var seen = new HashSet<string>();
        foreach (var r in boot.GetProperty("register_native").EnumerateArray())
        {
            var raw = Convert.ToUInt64(r.GetProperty("raw").GetString(), 16);
            if (raw > 0xFF) garbage++;
            if (!natives.TryGetValue(r.GetProperty("hash").GetString()!, out var n)) continue;
            named++;
            seen.Add(r.GetProperty("hash").GetString()!);
            if (r.GetProperty("argc").GetInt32() == n.Argc) equal++;
            else wrong.Add($"{n.Name} {r.GetProperty("argc").GetInt32()} (natives.json {n.Argc})");
        }
        // a native may be registered more than once (Kiln re-registers some): every one of natives.json must be seen,
        // and every call of a named one must carry its argc
        Check(calls >= 100 && seen.Count == natives.Count && equal == named,
            $"RegisterNative at boot: {calls} calls through a typed link, argc from the stack equals natives.json for {equal} of {named} calls of " +
            $"named natives ({seen.Count} of the {natives.Count} in natives.json seen; {calls - named} calls of others; {garbage} stack slots with garbage above the u8, masked)" +
            (wrong.Count > 0 ? $"; differ: {string.Join(", ", wrong.Take(5))}" : ""));
        var scales = boot.GetProperty("set_time_scale").EnumerateArray().ToList();
        if (scales.Count > 0)
            Check(true, $"SetTimeScale at boot: the game's call reached the typed link with scale {scales[0].GetProperty("scale").GetDouble():0.0000} (xmm1) " +
                        $"and now {scales[0].GetProperty("now").GetInt64()} (r8), daytime {scales[0].GetProperty("daytime").GetString()}");
        else
            Log.Info("hooks-typed-test: note: the game did not call SetTimeScale before the first step");
    }

    private void WrongDescriptor()
    {
        // two arguments for SetTimeScale: the second (ecsNow, an integer) where the function reads a float in xmm1
        var wrong = new SigDescriptor(SetTimeScale.Symbol, SigKind.Void, 0, false, SigInvoke.None,
            new SigArg("daytime", SigKind.Ptr, 8), new SigArg("ecsNow", SigKind.S64, 8));
        var r = TypedHooks.Detour(wrong, _ => { });
        Check(!r.Ok && r.Handle == null && (r.Reason ?? "").Contains("'ecsNow'"),
            $"a wrong descriptor (2 args for SetTimeScale) is refused naming 'ecsNow': {r.Reason}");
        if (r.Ok) r.Handle!.Remove();
    }

    private void TimeScale()
    {
        float scale = 0;
        long now = 0;
        nint daytime = 0;
        var seen = 0;
        var h = Hold(SetTimeScale.Detour((ref SetTimeScale.Call c) =>
        {
            if (c.Daytime != _fake) return;  // the game's own calls go on as they are
            seen++;
            scale = c.Scale;
            now = c.EcsNow;
            daytime = c.Daytime;
            c.Skip();  // the game's function never sees the stand-in: the clock is untouched
        }), "SetTimeScale.Detour");
        SetTimeScale.Invoke(_fake, 1.0f, 7050000141);
        Check(seen == 1 && scale == 1.0f && now == 7050000141 && daytime == _fake,
            $"SetTimeScale: the handler saw scale {scale:0.0} (xmm1) and now {now} (r8); Invoke round trip (the handler skipped: the clock untouched)");
        Drop(h);
        // a direct call that the game answers: GetGameTime of the server's Daytime the native part saw at boot (pure)
        if (_boot is { } b && b.GetProperty("set_time_scale").GetArrayLength() > 0)
        {
            var first = b.GetProperty("set_time_scale")[0];
            var dt = (nint)Convert.ToInt64(first.GetProperty("daytime").GetString(), 16);
            var t = GetGameTime.Invoke(dt, first.GetProperty("now").GetInt64());
            Check(t >= 0, $"GetGameTime.Invoke(the boot Daytime, its now) returns {t}");
        }
    }

    private void ItemVolume()
    {
        var v = Volume.Invoke(0);
        Check(v.Value == 18 && v.Has == 1, $"GetItemVolume: Invoke(null item) returns {{{v.Value}, has {v.Has}}} (the game's null branch, 18)");

        var after = Hold(Volume.Detour((ref Volume.Call c) =>
        {
            c.CallOriginal();
            if (c.Result.Has != 0) c.Result.Value = 64;
        }), "GetItemVolume.Detour");
        v = Volume.Invoke(0);
        Check(v.Value == 64, $"GetItemVolume: a handler sets Result.Value = 64 after the original: the caller gets {v.Value}");
        Drop(after);

        var second = 0;
        var hi = Hold(Volume.Detour((ref Volume.Call c) =>
        {
            c.Result.Value = 7;
            c.Result.Has = 1;
            c.Skip();
        }, priority: 10), "GetItemVolume.Detour (skip)");
        var lo = Hold(Volume.Detour((ref Volume.Call c) => second++, priority: 0), "GetItemVolume.Detour (second)");
        v = Volume.Invoke(0);
        Check(v.Value == 7 && second == 0, $"two handlers, the first skips: the second never runs (second ran {second} time(s), the caller got {v.Value})");
        Drop(hi);
        Drop(lo);

        var original = 0;
        hi = Hold(Volume.Detour((ref Volume.Call c) =>
        {
            c.CallOriginal();
            c.Result.Value = 999;
            throw new InvalidOperationException("hooks-typed-test: a handler that throws after CallOriginal (on purpose)");
        }, priority: 10), "GetItemVolume.Detour (fault)");
        // the rest of the chain behind the faulting handler: counts how often the original ran
        lo = Hold(Volume.Detour((ref Volume.Call c) => original++, priority: 0), "GetItemVolume.Detour (count)");
        v = Volume.Invoke(0);
        Check(v.Value == 18 && original == 1, $"fault after CallOriginal: original ran once ({original}), the caller got its result {v.Value}");
        Drop(hi);
        Drop(lo);
    }

    private void OwnFragment()
    {
        var s = Symbols.LoadShipped();
        var v = OwnVolume.Invoke(0);
        Check(s.SymbolsOk == 1 && Capabilities.Is(Volume.Capability) && v.Value == 18 && Symbols.Get(OwnVolume.Symbol) == Symbols.Get(Volume.Symbol),
            $"a descriptor of the mod's own fragment ({OwnVolume.Symbol}): generated, its code fit it at load, Invoke returns {v.Value}");
    }

    private void Cost()
    {
        // three rounds each way, alternating, after a warm-up long enough for the JIT's tiers; the best round of each
        const int n = 1_000_000;
        double Round()
        {
            var sw = Stopwatch.StartNew();
            for (var i = 0; i < n; i++) Volume.Invoke(0);
            return sw.Elapsed.TotalNanoseconds / n;
        }
        HookHandle? h = null;
        void Hook(bool on)
        {
            if (on) h = Hold(Volume.Detour((ref Volume.Call c) => { }), "GetItemVolume.Detour (cost)");
            else if (h != null) { Drop(h); h = null; }
        }
        Hook(true);
        for (var i = 0; i < 300_000; i++) Volume.Invoke(0);
        Hook(false);
        for (var i = 0; i < 300_000; i++) Volume.Invoke(0);
        double bare = double.MaxValue, hooked = double.MaxValue;
        for (var r = 0; r < 3; r++)
        {
            bare = Math.Min(bare, Round());
            Hook(true);
            hooked = Math.Min(hooked, Round());
            Hook(false);
        }
        Check(hooked > 0 && bare > 0, $"cost: {hooked - bare:0} ns per call over 1e6 calls (a managed typed pass-through on top of Invoke; " +
                                     $"best of 3 rounds: Invoke alone {bare:0} ns, with the hook {hooked:0} ns)");
    }

    private async Task Workers()
    {
        if (!Kiln.Testing.LabSystems.Enabled)
        {
            // a run for another row (the AV rows: exactly one control file); the worker row needs its own run with the switch
            _skipped.Add("typed hook on workers: the lab parallel switch is off (kiln/control/systems.parallel)");
            Log.Info($"hooks-typed-test: SKIP {_skipped[^1]}");
            return;
        }
        // The worker's direct call of a tick descriptor: SetTimeScale with the stand-in Daytime, and a handler that
        // skips every call with it stays on the whole window, so even a broken guard could not reach the game's function.
        var reached = 0;
        var guard = Hold(SetTimeScale.Detour((ref SetTimeScale.Call c) =>
        {
            if (c.Daytime != _fake) return;
            Interlocked.Increment(ref reached);
            c.Skip();
        }, priority: 100), "SetTimeScale.Detour (guard)");
        long calls = 0, faults = 0, offTick = 0;
        var threads = new System.Collections.Concurrent.ConcurrentDictionary<int, byte>();
        var tick = Environment.CurrentManagedThreadId;
        var refused = 0;
        var invoked = 0;
        var h = Hold(AttrChanged.Detour((ref AttrChanged.Call c) =>
        {
            Interlocked.Increment(ref calls);
            var id = Environment.CurrentManagedThreadId;
            threads.TryAdd(id, 0);
            if (id == tick || Game.IsTickThread) return;
            Interlocked.Increment(ref offTick);
            // a tick descriptor's direct call from a worker: refused before the call
            if (Interlocked.Exchange(ref invoked, 1) == 0)
            {
                try { SetTimeScale.Invoke(_fake, 1.0f, 0); }
                catch (InvalidOperationException) { Interlocked.Exchange(ref refused, 1); }
                catch (Exception) { Interlocked.Increment(ref faults); }
            }
        }), "AttrChanged.Detour");
        var forced = Kiln.Testing.LabSystems.ForceParallel(600);
        for (var i = 0; i < 620; i++) await Context.Scheduler.NextTick();
        Drop(h);
        Drop(guard);
        var workers = threads.Keys.Count(t => t != tick);
        Check(forced && calls > 0 && workers > 1 && faults == 0 && refused == 1 && reached == 0,
            $"typed hook on workers: {calls} calls on {threads.Count} threads ({workers} not the tick thread, {offTick} calls there), {faults} faults, " +
            (invoked == 0 ? "no call off the tick thread to try Invoke from" : refused == 1 ? "Invoke from a worker throws" : $"Invoke from a worker did NOT throw (reached the chain {reached} time(s))"));
    }
}
